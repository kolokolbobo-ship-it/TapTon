//! Safe HTTPS download of audio files on a background thread.
//!
//! Safety properties:
//! * only `https://` without credentials;
//! * every host is resolved first and rejected if ANY address is loopback/private/link-local/etc.;
//!   the checked addresses are then pinned into the HTTP client, so a second (rebinding) DNS answer
//!   cannot redirect the connection;
//! * automatic redirects are disabled; up to `MAX_REDIRECTS` are followed manually and each hop is
//!   validated again;
//! * system proxy settings are ignored (a proxy would resolve names itself and bypass the checks);
//! * 50 MiB size cap and 60 s total deadline; cooperative cancellation;
//! * the file name is generated by TapTone, never taken from the server or URL;
//! * content is sniffed (WAV/MP3) instead of trusting extension or Content-Type;
//! * partial files are always removed.

use crate::errors::DownloadError;
use crate::library::AudioFormat;
use crossbeam_channel::Sender;
use reqwest::blocking::Client;
use reqwest::header::{CONTENT_TYPE, LOCATION};
use reqwest::redirect::Policy;
use std::fs::{self, File};
use std::io::{ErrorKind, Read, Write};
use std::net::{IpAddr, Ipv4Addr, Ipv6Addr, SocketAddr, ToSocketAddrs};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;
use std::time::{Duration, Instant};
use url::{Host, Url};

pub const MAX_DOWNLOAD_BYTES: u64 = 50 * 1024 * 1024;
pub const MAX_REDIRECTS: usize = 3;
pub const CONNECT_TIMEOUT: Duration = Duration::from_secs(10);
pub const TOTAL_TIMEOUT: Duration = Duration::from_secs(60);

#[derive(Debug, Clone)]
pub struct DownloadedFile {
    pub path: PathBuf,
    pub format: AudioFormat,
    pub bytes: u64,
    /// Human-readable name derived from the URL (sanitized, without extension).
    pub suggested_name: String,
    /// The requested URL without query string or credentials; safe to store and log.
    pub source_url: String,
}

#[derive(Debug, Clone)]
pub enum DownloadEvent {
    Progress {
        id: u64,
        received: u64,
        total: Option<u64>,
    },
    Finished {
        id: u64,
        result: Result<DownloadedFile, DownloadError>,
    },
}

pub struct DownloadHandle {
    pub id: u64,
    cancel: Arc<AtomicBool>,
}

impl DownloadHandle {
    pub fn cancel(&self) {
        self.cancel.store(true, Ordering::Relaxed);
    }
}

/// URL without credentials, query and fragment, for logs and stored metadata.
pub fn redact_url(url: &Url) -> String {
    format!("{}://{}{}", url.scheme(), url.host_str().unwrap_or("?"), url.path())
}

fn v4_forbidden(ip: Ipv4Addr) -> bool {
    let o = ip.octets();
    ip.is_loopback()
        || ip.is_private()
        || ip.is_link_local()
        || ip.is_unspecified()
        || ip.is_broadcast()
        || ip.is_multicast()
        || ip.is_documentation()
        || o[0] == 0
        || (o[0] == 100 && (64..=127).contains(&o[1])) // CGNAT 100.64.0.0/10
        || (o[0] == 192 && o[1] == 0 && o[2] == 0) // 192.0.0.0/24
        || (o[0] == 198 && (o[1] == 18 || o[1] == 19)) // benchmarking
        || o[0] >= 240 // reserved
}

fn v6_forbidden(ip: Ipv6Addr) -> bool {
    if let Some(v4) = ip.to_ipv4_mapped() {
        return v4_forbidden(v4);
    }
    let s = ip.segments();
    // NAT64 64:ff9b::/96 embeds an IPv4 address.
    if s[0] == 0x0064 && s[1] == 0xff9b && s[2..6].iter().all(|x| *x == 0) {
        let v4 = Ipv4Addr::new((s[6] >> 8) as u8, s[6] as u8, (s[7] >> 8) as u8, s[7] as u8);
        return v4_forbidden(v4);
    }
    // 6to4 2002::/16 embeds an IPv4 address.
    if s[0] == 0x2002 {
        let v4 = Ipv4Addr::new((s[1] >> 8) as u8, s[1] as u8, (s[2] >> 8) as u8, s[2] as u8);
        return v4_forbidden(v4);
    }
    ip.is_loopback()
        || ip.is_unspecified()
        || ip.is_multicast()
        || (s[0] & 0xfe00) == 0xfc00 // unique local fc00::/7
        || (s[0] & 0xffc0) == 0xfe80 // link-local fe80::/10
        || (s[0] == 0x2001 && s[1] == 0x0db8) // documentation
}

/// True for loopback, private, link-local, CGNAT, multicast, reserved and similar addresses.
pub fn is_forbidden_ip(ip: IpAddr) -> bool {
    match ip {
        IpAddr::V4(v4) => v4_forbidden(v4),
        IpAddr::V6(v6) => v6_forbidden(v6),
    }
}

/// Static checks on a URL before any network access.
pub fn validate_url(url: &Url) -> Result<(), DownloadError> {
    if url.scheme() != "https" {
        return Err(DownloadError::UnsupportedScheme(url.scheme().to_string()));
    }
    if !url.username().is_empty() || url.password().is_some() {
        return Err(DownloadError::CredentialsInUrl);
    }
    match url.host() {
        None => Err(DownloadError::InvalidUrl("missing host".to_string())),
        Some(Host::Ipv4(ip)) if is_forbidden_ip(IpAddr::V4(ip)) => Err(DownloadError::ForbiddenAddress(IpAddr::V4(ip))),
        Some(Host::Ipv6(ip)) if is_forbidden_ip(IpAddr::V6(ip)) => Err(DownloadError::ForbiddenAddress(IpAddr::V6(ip))),
        Some(Host::Domain(d)) => {
            let d = d.trim_end_matches('.').to_ascii_lowercase();
            if d == "localhost" || d.ends_with(".localhost") || d.ends_with(".local") || d.ends_with(".internal") {
                Err(DownloadError::ForbiddenHost)
            } else {
                Ok(())
            }
        }
        _ => Ok(()),
    }
}

/// Resolve the URL's host and verify that every address is allowed.
pub fn resolve_checked(url: &Url) -> Result<Vec<SocketAddr>, DownloadError> {
    validate_url(url)?;
    let port = url.port_or_known_default().unwrap_or(443);
    let addrs: Vec<SocketAddr> = match url.host() {
        Some(Host::Ipv4(ip)) => vec![SocketAddr::new(IpAddr::V4(ip), port)],
        Some(Host::Ipv6(ip)) => vec![SocketAddr::new(IpAddr::V6(ip), port)],
        Some(Host::Domain(d)) => (d, port)
            .to_socket_addrs()
            .map_err(|e| DownloadError::DnsFailure {
                host: d.to_string(),
                reason: e.to_string(),
            })?
            .collect(),
        None => return Err(DownloadError::InvalidUrl("missing host".to_string())),
    };
    if addrs.is_empty() {
        return Err(DownloadError::DnsFailure {
            host: url.host_str().unwrap_or("?").to_string(),
            reason: "no addresses".to_string(),
        });
    }
    if let Some(bad) = addrs.iter().find(|a| is_forbidden_ip(a.ip())) {
        return Err(DownloadError::ForbiddenAddress(bad.ip()));
    }
    Ok(addrs)
}

pub fn enforce_limit(received: u64, limit: u64) -> Result<(), DownloadError> {
    if received > limit {
        Err(DownloadError::TooLarge {
            limit_mib: limit / (1024 * 1024),
        })
    } else {
        Ok(())
    }
}

/// Produce a file name that is safe on Windows: no separators or reserved characters, no reserved
/// device names, bounded length. Never empty.
pub fn safe_filename(raw: &str) -> String {
    let last = raw.rsplit(['/', '\\']).next().unwrap_or("");
    let cleaned: String = last
        .chars()
        .map(|c| {
            if c.is_control() || "<>:\"/\\|?*".contains(c) {
                '_'
            } else {
                c
            }
        })
        .collect();
    let trimmed: String = cleaned
        .trim_matches(|c: char| c == ' ' || c == '.')
        .chars()
        .take(64)
        .collect();
    if trimmed.is_empty() {
        return "sound".to_string();
    }
    let stem = trimmed.split('.').next().unwrap_or("").to_ascii_uppercase();
    let reserved = matches!(stem.as_str(), "CON" | "PRN" | "AUX" | "NUL")
        || ((stem.starts_with("COM") || stem.starts_with("LPT"))
            && stem.len() == 4
            && stem.as_bytes()[3].is_ascii_digit());
    if reserved {
        format!("_{trimmed}")
    } else {
        trimmed
    }
}

/// Display name (no extension) taken from the last path segment of the URL.
pub fn suggested_name(url: &Url) -> String {
    let seg = url.path_segments().and_then(|mut s| s.next_back()).unwrap_or("");
    let decoded: String = url::form_urlencoded::parse(format!("x={seg}").as_bytes())
        .next()
        .map(|(_, v)| v.into_owned())
        .unwrap_or_default();
    let safe = safe_filename(&decoded);
    Path::new(&safe)
        .file_stem()
        .and_then(|s| s.to_str())
        .filter(|s| !s.is_empty())
        .unwrap_or("sound")
        .to_string()
}

/// Remove leftover `.part` files (from a crash or cancelled download). Returns how many were removed.
pub fn cleanup_partials(dir: &Path) -> usize {
    let Ok(rd) = fs::read_dir(dir) else { return 0 };
    let mut n = 0;
    for entry in rd.flatten() {
        let p = entry.path();
        if p.extension().and_then(|e| e.to_str()) == Some("part") && fs::remove_file(&p).is_ok() {
            n += 1;
        }
    }
    n
}

struct PartFile {
    path: PathBuf,
    keep: bool,
}

impl Drop for PartFile {
    fn drop(&mut self) {
        if !self.keep {
            if let Err(e) = fs::remove_file(&self.path) {
                if e.kind() != ErrorKind::NotFound {
                    tracing::debug!("could not remove partial download {}: {e}", self.path.display());
                }
            }
        }
    }
}

fn verify_head(head: &[u8]) -> Result<AudioFormat, DownloadError> {
    if let Some(f) = AudioFormat::sniff(head) {
        return Ok(f);
    }
    let trimmed: Vec<u8> = head
        .iter()
        .copied()
        .skip_while(|b| b.is_ascii_whitespace())
        .take(1)
        .collect();
    if trimmed.first() == Some(&b'<') {
        Err(DownloadError::HtmlPage)
    } else {
        Err(DownloadError::NotAudio)
    }
}

fn map_reqwest(e: reqwest::Error) -> DownloadError {
    if e.is_timeout() {
        DownloadError::Timeout
    } else {
        // `without_url` keeps query strings (which may hold tokens) out of messages and logs.
        DownloadError::Network(e.without_url().to_string())
    }
}

fn build_client(url: &Url, addrs: &[SocketAddr]) -> Result<Client, DownloadError> {
    let mut b = Client::builder()
        .redirect(Policy::none())
        .no_proxy()
        .connect_timeout(CONNECT_TIMEOUT)
        .timeout(TOTAL_TIMEOUT)
        .user_agent(concat!("TapTone/", env!("CARGO_PKG_VERSION")));
    if let Some(Host::Domain(d)) = url.host() {
        b = b.resolve_to_addrs(d, addrs);
    }
    b.build().map_err(map_reqwest)
}

fn emit(tx: &Sender<DownloadEvent>, ev: DownloadEvent) {
    if tx.send(ev).is_err() {
        tracing::debug!("download event dropped: receiver is gone");
    }
}

fn run(
    id: u64,
    url: &Url,
    dest_dir: &Path,
    cancel: &AtomicBool,
    tx: &Sender<DownloadEvent>,
) -> Result<DownloadedFile, DownloadError> {
    let deadline = Instant::now() + TOTAL_TIMEOUT;
    let io = |e: std::io::Error| DownloadError::Io(e.to_string());

    let mut current = url.clone();
    let mut response = None;
    for hop in 0..=MAX_REDIRECTS {
        if cancel.load(Ordering::Relaxed) {
            return Err(DownloadError::Cancelled);
        }
        let addrs = resolve_checked(&current)?;
        let client = build_client(&current, &addrs)?;
        let r = client.get(current.as_str()).send().map_err(map_reqwest)?;
        if r.status().is_redirection() {
            if hop == MAX_REDIRECTS {
                return Err(DownloadError::TooManyRedirects);
            }
            let loc = r
                .headers()
                .get(LOCATION)
                .and_then(|v| v.to_str().ok())
                .ok_or(DownloadError::BadRedirect)?;
            current = current.join(loc).map_err(|_| DownloadError::BadRedirect)?;
            continue;
        }
        response = Some(r);
        break;
    }
    let mut resp = response.ok_or(DownloadError::TooManyRedirects)?;
    if !resp.status().is_success() {
        return Err(DownloadError::Http(resp.status().as_u16()));
    }
    let total = resp.content_length();
    if let Some(t) = total {
        enforce_limit(t, MAX_DOWNLOAD_BYTES)?;
    }
    if let Some(ct) = resp.headers().get(CONTENT_TYPE).and_then(|v| v.to_str().ok()) {
        if ct.to_ascii_lowercase().starts_with("text/html") {
            return Err(DownloadError::HtmlPage);
        }
    }

    fs::create_dir_all(dest_dir).map_err(io)?;
    let part = PartFile {
        path: dest_dir.join(format!("{}.part", uuid::Uuid::new_v4())),
        keep: false,
    };
    let mut file = File::create(&part.path).map_err(io)?;

    let mut buf = [0u8; 16 * 1024];
    let mut head: Vec<u8> = Vec::with_capacity(16);
    let mut format: Option<AudioFormat> = None;
    let mut received: u64 = 0;
    let mut last_emit = Instant::now();
    loop {
        if cancel.load(Ordering::Relaxed) {
            return Err(DownloadError::Cancelled);
        }
        if Instant::now() > deadline {
            return Err(DownloadError::Timeout);
        }
        let n = match resp.read(&mut buf) {
            Ok(0) => break,
            Ok(n) => n,
            Err(e) if e.kind() == ErrorKind::Interrupted => continue,
            Err(e) if e.kind() == ErrorKind::TimedOut => return Err(DownloadError::Timeout),
            Err(e) => return Err(DownloadError::Network(e.to_string())),
        };
        received += n as u64;
        enforce_limit(received, MAX_DOWNLOAD_BYTES)?;
        if format.is_none() {
            let take = (16 - head.len()).min(n);
            head.extend_from_slice(&buf[..take]);
            if head.len() >= 16 {
                format = Some(verify_head(&head)?);
            }
        }
        file.write_all(&buf[..n]).map_err(io)?;
        if last_emit.elapsed() >= Duration::from_millis(100) {
            emit(tx, DownloadEvent::Progress { id, received, total });
            last_emit = Instant::now();
        }
    }
    let format = match format {
        Some(f) => f,
        None => verify_head(&head)?,
    };
    file.sync_all().map_err(io)?;
    drop(file);

    let final_path = dest_dir.join(format!("{}.{}", uuid::Uuid::new_v4(), format.extension()));
    fs::rename(&part.path, &final_path).map_err(io)?;
    let mut part = part;
    part.keep = true;

    emit(
        tx,
        DownloadEvent::Progress {
            id,
            received,
            total: Some(received),
        },
    );
    Ok(DownloadedFile {
        path: final_path,
        format,
        bytes: received,
        suggested_name: suggested_name(url),
        source_url: redact_url(url),
    })
}

/// Start a download on a background thread. Progress and the final result arrive on `tx`.
pub fn spawn(id: u64, url: Url, dest_dir: PathBuf, tx: Sender<DownloadEvent>) -> DownloadHandle {
    let cancel = Arc::new(AtomicBool::new(false));
    let flag = Arc::clone(&cancel);
    let tx_thread = tx.clone();
    let spawned = std::thread::Builder::new()
        .name(format!("taptone-download-{id}"))
        .spawn(move || {
            tracing::info!("download {id} started: {}", redact_url(&url));
            let result = run(id, &url, &dest_dir, &flag, &tx_thread);
            if let Err(e) = &result {
                tracing::warn!("download {id} failed: {e}");
            }
            emit(&tx_thread, DownloadEvent::Finished { id, result });
        });
    if let Err(e) = spawned {
        emit(
            &tx,
            DownloadEvent::Finished {
                id,
                result: Err(DownloadError::Io(format!("could not start thread: {e}"))),
            },
        );
    }
    DownloadHandle { id, cancel }
}
